import fs from 'fs';
import { GoogleGenAI } from '@google/genai';
import 'dotenv/config';

// Initialize the new Google Gen AI SDK
const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });

async function generateAdvocateBrief() {
    try {
        console.log("Agent: Reading backend flags...");
        const rawData = fs.readFileSync('current_flags.json', 'utf-8');
        const flagsData = JSON.parse(rawData);

        console.log("Agent: Analyzing risk profile...");
        const prompt = `
        You are an expert Indian Property Law AI Assistant.
        Read the following JSON flags generated by our LandGuard Rules Engine:
        ${JSON.stringify(flagsData, null, 2)}
        
        Write a plain-English "Advocate Handoff Brief" for a citizen buyer.
        RULES:
        1. NEVER output the words "clean", "safe", or "verified title".
        2. Categorize the output into "Missing Documents to Request" and "Red Flags to Discuss with Your Lawyer".
        3. Explain the 'PARALLEL_CONVEYANCE' or 'BROKEN_OWNERSHIP_LINK' simply, without legal jargon.
        4. Include a "What we did not check" disclaimer (e.g., encumbrance certificates, physical possession).
        Output ONLY Markdown.
        `;

        // Generate content using the new SDK syntax
        const response = await ai.models.generateContent({
            model: 'gemini-2.5-flash',
            contents: prompt,
        });

        fs.writeFileSync('advocate_brief.md', response.text);
        console.log("Agent: Advocate Handoff Brief generated successfully.");

    } catch (error) {
        console.error("Agent Error:", error.message);
        process.exit(1);
    }
}

generateAdvocateBrief();


